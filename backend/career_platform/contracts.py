"""Version 1 shared value objects. Changes require integration-owner review."""
from dataclasses import dataclass
from typing import Any, Protocol

CONTRACT_VERSION = '1'
QUESTION_INDEX = 'career_platform_questions_v1'


@dataclass(frozen=True)
class Evidence:
    source_id: str
    field_path: str
    quote: str


@dataclass(frozen=True)
class RankedQuestion:
    question_id: str
    question: str
    key_points: tuple[str, ...]
    evidence: tuple[Evidence, ...]
    score: float
    origin: str = 'catalog'


class CatalogPort(Protocol):
    def companies(self, *, user, data: dict) -> dict: ...
    def jobs(self, *, user, data: dict) -> dict: ...
    def questions(self, *, user, data: dict) -> dict: ...
    def import_batch(self, *, user, data: dict) -> dict: ...


class EvaluationPort(Protocol):
    def run(self, *, user, data: dict) -> dict: ...
    def list_runs(self, *, user, data: dict) -> dict: ...
    def get_run(self, *, user, data: dict) -> dict: ...
    def export(self, *, user, data: dict) -> dict: ...


class ResumeAnalysisPort(Protocol):
    def analyze(self, *, user, data: dict) -> dict: ...
    def list_runs(self, *, user, data: dict) -> dict: ...
    def get_run(self, *, user, data: dict) -> dict: ...
    def apply(self, *, user, data: dict) -> dict: ...


class RetrievalStrategy(Protocol):
    def retrieve(self, *, query: str, role: str, topic: str, difficulty: str, top_k: int) -> list[RankedQuestion]: ...


class InterviewRagPort(Protocol):
    def retrieve(self, *, user, data: dict) -> dict: ...
    def answer(self, *, user, data: dict) -> dict: ...


class PracticeStore(Protocol):
    def start(self, *, user, data: dict) -> dict: ...
    def list_sessions(self, *, user, data: dict) -> dict: ...
    def get_session(self, *, user, data: dict) -> dict: ...
    def finish(self, *, user, data: dict) -> dict: ...
    def record_answer(self, *, user, data: dict) -> dict: ...
    def record_feedback(self, *, user, data: dict) -> dict: ...


class ModelGateway(Protocol):
    def generate(self, *, system: str, payload: dict[str, Any]) -> dict: ...


class RankingStrategy(Protocol):
    def rank(self, *, query: str, top_k: int) -> list[str]: ...


class EvaluationDatasetLoader(Protocol):
    def load(self, version: str) -> dict: ...
